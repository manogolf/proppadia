#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'USAGE'
Run NHL SOG arm bakeoff only when slate game count meets threshold.

Usage:
  bin/nhl_bakeoff_trigger.sh [--slate-date YYYY-MM-DD] [--min-games N] [--events-json PATH]
                             [--disable-base-v2-arm] [--strict-calibration] [--strict-arms]
                             [--dry-run]

Defaults:
  --slate-date       $(date +%F)
  --min-games        8
  --events-json      nhl/site/data/events_today.json
  base_v2 arm        enabled

Notes:
  - Reads game count from events JSON generated by NHL daily pipeline.
  - If game_count < min-games, exits 0 with a skip message.
USAGE
}

SLATE_DATE="$(date +%F)"
MIN_GAMES=8
EVENTS_JSON="nhl/site/data/events_today.json"
ENABLE_BASE_V2=1
STRICT_CAL=0
STRICT_ARMS=0
DRY_RUN=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --slate-date)
      SLATE_DATE="${2:-}"
      shift 2
      ;;
    --min-games)
      MIN_GAMES="${2:-}"
      shift 2
      ;;
    --events-json)
      EVENTS_JSON="${2:-}"
      shift 2
      ;;
    --disable-base-v2-arm)
      ENABLE_BASE_V2=0
      shift
      ;;
    --strict-calibration)
      STRICT_CAL=1
      shift
      ;;
    --strict-arms)
      STRICT_ARMS=1
      shift
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    -h|--help|help)
      usage
      exit 0
      ;;
    *)
      echo "[nhl-bakeoff-trigger] unknown arg: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if ! [[ "$MIN_GAMES" =~ ^[0-9]+$ ]]; then
  echo "[nhl-bakeoff-trigger] --min-games must be an integer, got '$MIN_GAMES'" >&2
  exit 2
fi

if [[ -z "$SLATE_DATE" ]]; then
  echo "[nhl-bakeoff-trigger] empty --slate-date" >&2
  exit 2
fi

if [[ ! -f "$EVENTS_JSON" ]]; then
  echo "[nhl-bakeoff-trigger] events json not found: $EVENTS_JSON" >&2
  exit 2
fi

GAME_COUNT="$(
python - "$EVENTS_JSON" <<'PY'
import json
import sys
from pathlib import Path

p = Path(sys.argv[1])
obj = json.loads(p.read_text())
if isinstance(obj, list):
    rows = [x for x in obj if isinstance(x, dict)]
    print(len(rows))
else:
    print(0)
PY
)"

if ! [[ "$GAME_COUNT" =~ ^[0-9]+$ ]]; then
  echo "[nhl-bakeoff-trigger] could not parse game_count from $EVENTS_JSON (got '$GAME_COUNT')" >&2
  exit 2
fi

echo "[nhl-bakeoff-trigger] slate_date=$SLATE_DATE game_count=$GAME_COUNT min_games=$MIN_GAMES events_json=$EVENTS_JSON"

if (( GAME_COUNT < MIN_GAMES )); then
  echo "[nhl-bakeoff-trigger] skip: game_count ($GAME_COUNT) < min_games ($MIN_GAMES)"
  exit 0
fi

cmd=(.venv/bin/python backend/nhl/scripts/run_sog_candidate_arm_bakeoff.py --slate-date "$SLATE_DATE")
if (( ENABLE_BASE_V2 == 1 )); then
  cmd+=(--enable-base-v2-arm)
fi
if (( STRICT_CAL == 1 )); then
  cmd+=(--strict-calibration)
fi
if (( STRICT_ARMS == 1 )); then
  cmd+=(--strict-arms)
fi

echo "[nhl-bakeoff-trigger] run: PYTHONPATH=. ${cmd[*]}"
if (( DRY_RUN == 1 )); then
  echo "[nhl-bakeoff-trigger] dry-run enabled; command not executed."
  exit 0
fi

PYTHONPATH=. "${cmd[@]}"

